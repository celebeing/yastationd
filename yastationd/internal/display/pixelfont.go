package display

import "unicode"

// Bitmap fonts for text on a pixel screen (pixeltext.go): font7, 7 rows, for one line in the
// middle of orion's 12 rows; font5, 5 rows, for two lines. Upper case only (lower case is drawn
// as upper case), Latin and Cyrillic, digits, punctuation. Cyrillic letters that look like Latin
// ones reuse them (fontAlias). Rows: '#' on, anything else off.

type pfont struct {
	h      int
	space  int // the width of ' '
	glyphs map[rune]bitmap
}

// fontAlias: Cyrillic capitals drawn with the Latin glyph of the same shape.
var fontAlias = map[rune]rune{'А': 'A', 'В': 'B', 'Е': 'E', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O',
	'Р': 'P', 'С': 'C', 'Т': 'T', 'Х': 'X', '–': '-', '−': '-', '‐': '-', '‘': '\'', '’': '\'',
	'“': '"', '”': '"', '„': '"', '×': 'x', '…': '…'}

// glyph is r's bitmap: upper case, aliases, else a hollow box.
func (f pfont) glyph(r rune) bitmap {
	r = unicode.ToUpper(r)
	if a, ok := fontAlias[r]; ok {
		r = a
	}
	if g, ok := f.glyphs[r]; ok {
		return g
	}
	if r == 'X' || r == 'x' {
		return f.glyphs['X']
	}
	return f.glyphs[0]
}

